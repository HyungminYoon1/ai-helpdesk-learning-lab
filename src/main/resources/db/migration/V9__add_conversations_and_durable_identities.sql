CREATE TABLE helpdesk_user_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_key UUID NOT NULL UNIQUE,
    login_username TEXT NOT NULL UNIQUE CHECK (btrim(login_username) <> '')
);

ALTER TABLE tickets ADD COLUMN requester_user_id BIGINT
    REFERENCES helpdesk_user_identities (id);
CREATE INDEX tickets_requester_user_idx ON tickets (requester_user_id);

ALTER TABLE ticket_messages
    ADD COLUMN author_user_id BIGINT REFERENCES helpdesk_user_identities (id),
    ADD COLUMN message_type VARCHAR(32) NOT NULL DEFAULT 'INQUIRY',
    ADD COLUMN client_request_id UUID,
    ADD COLUMN corrects_message_id BIGINT,
    ADD CONSTRAINT message_kind_fields CHECK (
        (message_type = 'INQUIRY' AND client_request_id IS NULL AND corrects_message_id IS NULL)
        OR (message_type = 'OFFICIAL_REPLY' AND author_user_id IS NOT NULL AND client_request_id IS NOT NULL)
    ),
    ADD CONSTRAINT message_ticket_identity UNIQUE (ticket_id, id),
    ADD CONSTRAINT message_correction_same_ticket FOREIGN KEY (ticket_id, corrects_message_id)
        REFERENCES ticket_messages (ticket_id, id),
    ADD CONSTRAINT message_correction_not_self CHECK (corrects_message_id IS NULL OR corrects_message_id <> id);

CREATE UNIQUE INDEX message_submission_unique
    ON ticket_messages (ticket_id, author_user_id, client_request_id)
    WHERE client_request_id IS NOT NULL;
CREATE INDEX message_author_user_idx ON ticket_messages (author_user_id);
CREATE INDEX message_correction_idx ON ticket_messages (ticket_id, corrects_message_id)
    WHERE corrects_message_id IS NOT NULL;
-- The (ticket_id, id) unique index also supports chronological bounded reads.
-- No historical owner is inferred from a name or an AI Job.
