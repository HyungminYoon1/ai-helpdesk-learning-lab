CREATE TABLE support_services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE CHECK (btrim(code) <> ''),
    display_name TEXT NOT NULL CHECK (btrim(display_name) <> '')
);

CREATE TABLE support_service_memberships (
    service_id BIGINT NOT NULL REFERENCES support_services(id),
    user_id BIGINT NOT NULL REFERENCES helpdesk_user_identities(id),
    display_name TEXT NOT NULL CHECK (btrim(display_name) <> ''),
    support_role TEXT NOT NULL CHECK (support_role IN ('AGENT', 'SUPERVISOR')),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (service_id, user_id)
);
CREATE INDEX support_membership_user_idx ON support_service_memberships(user_id, service_id);

-- No inferred historical service, assignee or membership backfill.
ALTER TABLE tickets
    ADD COLUMN service_id BIGINT REFERENCES support_services(id),
    ADD COLUMN assignee_user_id BIGINT,
    ADD COLUMN assignment_version BIGINT NOT NULL DEFAULT 0 CHECK (assignment_version >= 0),
    ADD CONSTRAINT ticket_service_id_unique UNIQUE (service_id, id),
    ADD CONSTRAINT ticket_assignee_membership FOREIGN KEY (service_id, assignee_user_id)
        REFERENCES support_service_memberships(service_id, user_id),
    ADD CONSTRAINT ticket_assignment_state CHECK (
        (assignee_user_id IS NULL AND assignment_version = 0)
        OR (service_id IS NOT NULL AND assignee_user_id IS NOT NULL AND assignment_version > 0)
    );
CREATE INDEX ticket_service_assignee_idx ON tickets(service_id, assignee_user_id, id);

CREATE TABLE ticket_assignment_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL,
    ticket_id BIGINT NOT NULL,
    actor_user_id BIGINT NOT NULL,
    client_request_id UUID NOT NULL,
    operation TEXT NOT NULL CHECK (operation IN ('CLAIM', 'TRANSFER')),
    expected_version BIGINT NOT NULL CHECK (expected_version >= 0),
    resulting_version BIGINT NOT NULL CHECK (resulting_version > 0),
    from_user_id BIGINT,
    to_user_id BIGINT NOT NULL,
    reason TEXT,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (ticket_id, actor_user_id, client_request_id),
    UNIQUE (ticket_id, resulting_version),
    CHECK (resulting_version = expected_version + 1),
    CHECK (
        (operation = 'CLAIM' AND from_user_id IS NULL AND to_user_id = actor_user_id AND reason IS NULL)
        OR (operation = 'TRANSFER' AND from_user_id IS NOT NULL AND to_user_id <> from_user_id
            AND reason IS NOT NULL AND btrim(reason) <> '' AND char_length(reason) <= 500)
    ),
    FOREIGN KEY (service_id, ticket_id) REFERENCES tickets(service_id, id),
    FOREIGN KEY (service_id, actor_user_id) REFERENCES support_service_memberships(service_id, user_id),
    FOREIGN KEY (service_id, from_user_id) REFERENCES support_service_memberships(service_id, user_id),
    FOREIGN KEY (service_id, to_user_id) REFERENCES support_service_memberships(service_id, user_id)
);
CREATE INDEX assignment_event_ticket_id_idx ON ticket_assignment_events(ticket_id, id);
CREATE INDEX assignment_event_actor_idx ON ticket_assignment_events(service_id, actor_user_id);
CREATE INDEX assignment_event_from_idx ON ticket_assignment_events(service_id, from_user_id);
CREATE INDEX assignment_event_to_idx ON ticket_assignment_events(service_id, to_user_id);

ALTER TABLE ticket_messages
    ADD COLUMN reply_assignment_version BIGINT CHECK (reply_assignment_version > 0),
    ADD CONSTRAINT reply_assignment_event FOREIGN KEY (ticket_id, reply_assignment_version)
        REFERENCES ticket_assignment_events(ticket_id, resulting_version),
    ADD CONSTRAINT inquiry_without_reply_assignment_version CHECK (
        message_type <> 'INQUIRY' OR reply_assignment_version IS NULL
    );
CREATE INDEX message_assignment_event_idx ON ticket_messages(ticket_id, reply_assignment_version);
