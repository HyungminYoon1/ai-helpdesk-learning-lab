-- 적용한 V1~V3와 접수 원문은 변경하지 않는다.
ALTER TABLE ai_suggestion_jobs
    DROP CONSTRAINT ai_suggestion_jobs_status_allowed,
    DROP CONSTRAINT ai_suggestion_jobs_finished_valid,
    ADD CONSTRAINT ai_suggestion_jobs_status_allowed
        CHECK (status IN ('PENDING', 'RUNNING', 'FAILED', 'SUCCEEDED', 'ABSTAINED')),
    ADD CONSTRAINT ai_suggestion_jobs_finished_valid
        CHECK ((status = 'FAILED' AND finished_at IS NOT NULL AND last_failure_code IS NOT NULL)
            OR (status IN ('SUCCEEDED', 'ABSTAINED') AND finished_at IS NOT NULL
                    AND last_failure_code IS NULL AND current_attempt > 0)
            OR (status IN ('PENDING', 'RUNNING') AND finished_at IS NULL));

CREATE TABLE ticket_suggestions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES ai_suggestion_jobs (id),
    summary TEXT NOT NULL,
    priority VARCHAR(32) NOT NULL,
    review_status VARCHAR(32) NOT NULL DEFAULT 'PENDING_REVIEW',
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT ticket_suggestions_job_unique UNIQUE (job_id),
    -- Java 검증기의 ECMAScript trim 공백 집합과 같은 공백만으로 된 요약을 거부한다.
    CONSTRAINT ticket_suggestions_summary_not_blank CHECK (
        btrim(summary, U&'\0009\000A\000B\000C\000D\0020\00A0\1680\2000\2001\2002\2003\2004\2005\2006\2007\2008\2009\200A\2028\2029\202F\205F\3000\FEFF') <> ''),
    CONSTRAINT ticket_suggestions_priority_allowed
        CHECK (priority IN ('NORMAL', 'HIGH', 'UNDETERMINED')),
    CONSTRAINT ticket_suggestions_review_status_allowed
        CHECK (review_status = 'PENDING_REVIEW')
);

CREATE TABLE ticket_suggestion_categories (
    suggestion_id BIGINT NOT NULL REFERENCES ticket_suggestions (id),
    category VARCHAR(32) NOT NULL,
    PRIMARY KEY (suggestion_id, category),
    CONSTRAINT ticket_suggestion_categories_category_allowed
        CHECK (category IN ('ACCOUNT', 'BILLING', 'TECHNICAL', 'OTHER', 'UNDETERMINED'))
);

