-- Baseline zero preserves existing status; it does not invent historical events.
ALTER TABLE tickets ADD COLUMN status_version BIGINT NOT NULL DEFAULT 0 CHECK (status_version >= 0);

CREATE TABLE ticket_status_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES tickets(id),
    actor_user_id BIGINT NOT NULL REFERENCES helpdesk_user_identities(id),
    client_request_id UUID NOT NULL,
    request_scope TEXT NOT NULL CHECK (request_scope IN ('STAFF','REQUESTER')),
    operation TEXT NOT NULL CHECK (operation IN ('START','RESOLVE','REOPEN')),
    expected_status_version BIGINT NOT NULL CHECK (expected_status_version >= 0 AND expected_status_version < 9223372036854775807),
    resulting_status_version BIGINT NOT NULL CHECK (resulting_status_version > 0),
    expected_assignment_version BIGINT,
    assignment_version BIGINT NOT NULL CHECK (assignment_version >= 0),
    assignment_event_version BIGINT GENERATED ALWAYS AS (NULLIF(assignment_version,0)) STORED,
    from_status TEXT NOT NULL,
    to_status TEXT NOT NULL,
    reason TEXT NOT NULL CHECK (btrim(reason) <> '' AND char_length(reason) <= 500),
    related_reply_message_id BIGINT,
    through_customer_message_id BIGINT,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT status_event_submission_unique UNIQUE (ticket_id,actor_user_id,client_request_id),
    CONSTRAINT status_event_version_unique UNIQUE (ticket_id,resulting_status_version),
    CHECK (resulting_status_version = expected_status_version + 1),
    CHECK (
        (request_scope='STAFF' AND expected_assignment_version IS NOT NULL
            AND expected_assignment_version > 0 AND expected_assignment_version=assignment_version)
        OR (request_scope='REQUESTER' AND operation='REOPEN' AND expected_assignment_version IS NULL)
    ),
    CHECK (
        (operation='START' AND from_status='OPEN' AND to_status='IN_PROGRESS')
        OR (operation='RESOLVE' AND from_status='IN_PROGRESS' AND to_status='RESOLVED')
        OR (operation='REOPEN' AND from_status='RESOLVED' AND to_status='OPEN')
    ),
    CHECK (
        (operation='RESOLVE' AND related_reply_message_id IS NOT NULL AND related_reply_message_id > 0
            AND through_customer_message_id IS NOT NULL AND through_customer_message_id > 0)
        OR (operation <> 'RESOLVE' AND related_reply_message_id IS NULL AND through_customer_message_id IS NULL)
    ),
    FOREIGN KEY (ticket_id,assignment_event_version) REFERENCES ticket_assignment_events(ticket_id,resulting_version),
    FOREIGN KEY (ticket_id,related_reply_message_id) REFERENCES ticket_messages(ticket_id,id),
    FOREIGN KEY (ticket_id,through_customer_message_id) REFERENCES ticket_messages(ticket_id,id)
);
CREATE INDEX status_event_ticket_id_idx ON ticket_status_events(ticket_id,id);
CREATE INDEX status_event_actor_idx ON ticket_status_events(actor_user_id);
CREATE INDEX status_event_assignment_idx ON ticket_status_events(ticket_id,assignment_event_version);
CREATE INDEX status_event_reply_idx ON ticket_status_events(ticket_id,related_reply_message_id);
CREATE INDEX status_event_customer_idx ON ticket_status_events(ticket_id,through_customer_message_id);
