CREATE TABLE ticket_customer_message_confirmations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL CHECK (ticket_id > 0),
    assignment_version BIGINT NOT NULL CHECK (assignment_version > 0),
    actor_user_id BIGINT NOT NULL REFERENCES helpdesk_user_identities(id),
    client_request_id UUID NOT NULL,
    through_message_id BIGINT NOT NULL CHECK (through_message_id > 0),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT confirmation_submission_unique UNIQUE (ticket_id, actor_user_id, client_request_id),
    CONSTRAINT confirmation_assignment_same_ticket FOREIGN KEY (ticket_id, assignment_version)
        REFERENCES ticket_assignment_events(ticket_id, resulting_version),
    CONSTRAINT confirmation_message_same_ticket FOREIGN KEY (ticket_id, through_message_id)
        REFERENCES ticket_messages(ticket_id, id)
);

-- One append-only record per explicit submission, no historical confirmation backfill.
-- Current progress is MAX(through_message_id) within the current assignment, not MAX(id).
CREATE INDEX confirmation_assignment_progress_idx
    ON ticket_customer_message_confirmations(ticket_id, assignment_version, through_message_id DESC);
CREATE INDEX confirmation_message_idx ON ticket_customer_message_confirmations(ticket_id, through_message_id);
CREATE INDEX confirmation_actor_idx ON ticket_customer_message_confirmations(actor_user_id);
